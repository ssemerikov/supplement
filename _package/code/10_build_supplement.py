#!/usr/bin/env python3
"""Assemble the submission supplement, and refuse to include what must not leave this machine.

    python3 code/10_build_supplement.py [--out supplement/_package] [--force]

WHY THIS IS A SCRIPT AND NOT A FOLDER OF COPIES. A supplement maintained by
hand drifts: the code in it stops matching the code that produced the numbers,
and nobody notices because both look plausible. This assembles the package from
the working tree on demand, records a SHA-256 for every file it copies, and can
be re-run after any change.

The second reason is that some things in this repository MUST NOT ship, and a
manual copy is exactly where that goes wrong:

  data/userID     the author's personal ESS API credential. A secret. Never
                  ships, never goes to OSF, never enters a replication package.
  data/qog/       Quality of Government prohibits redistribution; point readers
                  at the original source instead.
  data/hofstede/  redistribution terms unclear, so treated as prohibited.
  survey microdata (ZA7505, ESS .sav) -- licensed to the downloader, not ours to
                  redistribute. docs/data-provenance.md records version, access
                  date and licence so a reader can obtain the identical file.

The exclusions are enforced by an explicit deny-list checked against every
candidate path AND by a secret scan of every text file copied. The scan exists
because a deny-list only stops files you thought of; a key pasted into a
notebook or a log is the failure mode it cannot see. If the scan trips, the
build aborts rather than writing a package.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# --- what ships ------------------------------------------------------------------------
# (source relative to ROOT, destination relative to the package, description)
INCLUDE: list[tuple[str, str, str]] = [
    ("code", "code", "every analysis script, verbatim"),
    ("supplement/analysis", "analysis", "full model output as emitted (JSON)"),
    ("supplement/tier2-forecast", "tier2-forecast",
     "every Delphi prompt verbatim, the instrument, and all forecast runs"),
    ("supplement/negative-result-section-as-drafted.tex",
     "S1-negative-result-section-as-drafted.tex",
     "the pre-registered negative-result section, as drafted before the analysis"),
    ("docs/design/item-table-v2-joint-names.md", "S2-item-table.md",
     "the frozen item table, hash-locked and reproduced by code/01"),
    ("docs/preregistration.md", "S3-preregistration.md",
     "the pre-registration as maintained, including all deviations"),
    ("docs/data-provenance.md", "S4-data-provenance.md",
     "dataset versions, access dates, licences and checksums"),
    ("docs/environment-verification.md", "S5-environment.md",
     "package versions and the install recipe"),
    ("docs/ethics.md", "S6-ethics.md", "no-participants record"),
    ("supplement/sphere-reliability-table.md", "S7-sphere-reliability.md",
     "per-sphere reliability, generated by code/17 and cited from the Results"),
    ("supplement/delphi-check-2.md", "S8-delphi-check-2-temporal.md",
     "temporal replication protocol and results, generated by code/28"),
    ("supplement/delphi-checks-4-5.md", "S8-delphi-checks-4-5.md",
     "contamination and sycophancy protocols and results, generated by code/21"),
    ("supplement/reporting-checklists.md", "S9-reporting-checklists.md",
     "completed ACCORD, CREDES and TRIPOD-LLM checklists"),
    ("docs/design/ess-item-table-frozen.md", "S10-ess-item-table.md",
     "the ESS replication item table, frozen and hashed before any ESS model was fitted"),
    # code/02 is shipped and reads these two; without them the code-availability statement
    # ("runs against the archived datasets without modification") is false. They are the pilot
    # elicitation script and its raw output, neither licensed nor personal.
    ("docs/design/delphi-pilot.py", "delphi-pilot/delphi-pilot.py",
     "the pilot elicitation script, the input to code/02"),
    ("docs/design/delphi-pilot_raw.json", "delphi-pilot/delphi-pilot_raw.json",
     "the pilot's raw responses, the input to code/02"),
]

# --- what must never ship --------------------------------------------------------------
DENY_PATHS = {
    "data/userID",          # ESS API credential -- a secret
}
DENY_DIRS = {
    "data/qog",             # redistribution prohibited
    "data/hofstede",        # redistribution terms unclear
    "data/vdem",
    "data/welzel",
    "data/derived",         # derived from licensed microdata
    "__pycache__",
    ".fitcache",            # 250 MB of fitted lavaan objects; regenerable
}
DENY_SUFFIXES = {".sav", ".dta", ".rds", ".pyc"}

# Patterns that indicate a credential has leaked into a text file. Deliberately
# broad: a false positive costs one look, a false negative publishes a key.
SECRET_PATTERNS = [
    (re.compile(r"sk-[A-Za-z0-9]{8,}"), "OpenAI-style API key"),
    (re.compile(r"(?i)\b(api[_-]?key|apikey|secret|passwd|password|token)\s*[=:]\s*"
                r"['\"][^'\"\s]{8,}['\"]"), "assigned credential literal"),
    (re.compile(r"(?i)\bBearer\s+[A-Za-z0-9._\-]{20,}"), "bearer token"),
    (re.compile(r"ghp_[A-Za-z0-9]{20,}"), "GitHub token"),
]
# Lines that merely NAME the environment variable are fine and expected.
SECRET_ALLOW = re.compile(r"os\.environ|getenv|Sys\.getenv|\$\{?[A-Z_]+\}?|<REDACTED>|xxx+",
                          re.IGNORECASE)


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def denied(rel: Path) -> str | None:
    s = rel.as_posix()
    if s in DENY_PATHS:
        return "deny-list (secret)"
    for d in DENY_DIRS:
        if s == d or f"/{d}/" in f"/{s}/":
            return f"deny-list directory {d}"
    if rel.suffix in DENY_SUFFIXES:
        return f"deny-list suffix {rel.suffix}"
    return None


def scan_secrets(p: Path) -> list[str]:
    try:
        text = p.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return []
    # Display path only. Must not raise: this function is a security guard, and a guard
    # that throws on an unexpected path is a guard that silently does not run. Paths
    # outside ROOT arrive when the scanner is exercised by its own negative test.
    try:
        shown = p.relative_to(ROOT)
    except ValueError:
        shown = p
    hits = []
    for i, line in enumerate(text.splitlines(), 1):
        if SECRET_ALLOW.search(line):
            continue
        for pat, label in SECRET_PATTERNS:
            if pat.search(line):
                hits.append(f"{shown}:{i}: {label}")
    return hits


def gather(src: Path) -> list[Path]:
    if src.is_file():
        return [src]
    return sorted(f for f in src.rglob("*") if f.is_file())


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="supplement/_package")
    ap.add_argument("--force", action="store_true",
                    help="overwrite an existing package directory")
    args = ap.parse_args()

    out = ROOT / args.out
    if out.exists():
        if not args.force:
            print(f"FAIL  {out.relative_to(ROOT)} exists; pass --force to replace it")
            return 2
        shutil.rmtree(out)

    manifest: list[dict] = []
    secrets: list[str] = []
    skipped: list[str] = []

    for src_rel, dst_rel, desc in INCLUDE:
        src = ROOT / src_rel
        if not src.exists():
            print(f"  --    missing, skipped: {src_rel}")
            skipped.append(src_rel)
            continue
        for f in gather(src):
            rel_in_src = f.relative_to(src) if src.is_dir() else Path(f.name)
            rel = f.relative_to(ROOT)
            why = denied(rel)
            if why:
                skipped.append(f"{rel} ({why})")
                continue
            secrets.extend(scan_secrets(f))
            dst = out / dst_rel / rel_in_src if src.is_dir() else out / dst_rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, dst)
            manifest.append({
                "path": str(dst.relative_to(out)),
                "source": str(rel),
                "bytes": f.stat().st_size,
                "sha256": sha256(f),
                "group": desc,
            })

    if secrets:
        shutil.rmtree(out, ignore_errors=True)
        print("\nABORTED -- possible credential in a file selected for the supplement:")
        for s in secrets:
            print(f"    {s}")
        print("\nNo package written. Remove the secret, then re-run.")
        return 1

    # BLINDING. Quality & Quantity reviews double-blind and makes anonymising "associated
    # materials" the author's responsibility, so an OSF node URL in the supplement unblinds the
    # submission just as surely as a name would -- every one of ezjh2/byjn2/zrvdp resolves to a
    # named account. This WARNS rather than aborts, and never edits a file, because the package
    # is dual-purpose: the review copy must be anonymised, the archival copy must keep the real
    # DOIs, and which one is being built is a decision for whoever is submitting. Stripping the
    # links automatically would silently damage the reproducibility record to satisfy a
    # requirement that does not apply to every build.
    unblinding: dict[str, int] = {}
    for m in manifest:
        f = out / m["path"]
        try:
            hits = len(re.findall(r"osf\.io/|OSF\.IO/", f.read_text(errors="ignore")))
        except (OSError, UnicodeDecodeError):
            continue
        if hits:
            unblinding[m["path"]] = hits

    meta = {
        "built_utc": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
        "blinding": {
            "review_model": "double-blind (Quality & Quantity)",
            "identifying_links_present": bool(unblinding),
            "files_with_osf_links": unblinding,
            "action_required": ("Before uploading as a REVIEW copy, replace OSF node URLs with "
                                "anonymised view-only links. Keep the real DOIs for the "
                                "camera-ready and archival copies."),
        },
        "n_files": len(manifest),
        "total_bytes": sum(m["bytes"] for m in manifest),
        "excluded": sorted(set(skipped)),
        "exclusion_reasons": {
            "data/userID": "author's personal ESS API credential -- a secret",
            "data/qog": "Quality of Government prohibits redistribution",
            "data/hofstede": "redistribution terms unclear; treated as prohibited",
            "survey microdata": ("licensed to the downloader; docs/data-provenance.md gives "
                                 "version, access date and licence so the identical file can "
                                 "be obtained from the original source"),
            ".fitcache": "regenerable fitted model objects, ~250 MB",
        },
        "files": manifest,
    }
    (out / "MANIFEST.json").write_text(json.dumps(meta, indent=1))

    print(f"  {len(manifest)} files -> {out.relative_to(ROOT)}")
    print(f"  {meta['total_bytes'] / 1e6:.1f} MB")
    print(f"  {len(meta['excluded'])} path(s) excluded by policy")
    print("  secret scan: clean")
    print(f"  wrote {(out / 'MANIFEST.json').relative_to(ROOT)}")
    if unblinding:
        n = sum(unblinding.values())
        print(f"\n  WARNING -- blinding: {n} OSF link(s) in {len(unblinding)} file(s) identify the")
        print("  authors. Quality & Quantity reviews double-blind. Replace them with anonymised")
        print("  view-only links in the REVIEW copy; keep the real DOIs for the archival copy.")
        for p in sorted(unblinding):
            print(f"    {unblinding[p]:>3}  {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
